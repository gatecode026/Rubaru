require('dotenv').config({ path: require('path').join(__dirname, '../.env') });
const imagekitService = require('../services/imagekitService');

async function testImageKitIntegration() {
  console.log('--- STARTING IMAGEKIT INTEGRATION TEST ---');
  console.log('Using ImageKit URL Endpoint:', process.env.IMAGEKIT_URL_ENDPOINT);
  console.log('Using Public Key:', process.env.IMAGEKIT_PUBLIC_KEY ? 'Present (***' + process.env.IMAGEKIT_PUBLIC_KEY.slice(-6) + ')' : 'MISSING');

  // Minimal valid 1x1 JPEG buffer
  const sample1x1Jpg = Buffer.from([
    0xff, 0xd8, 0xff, 0xe0, 0x00, 0x10, 0x4a, 0x46, 0x49, 0x46, 0x00, 0x01,
    0x01, 0x01, 0x00, 0x48, 0x00, 0x48, 0x00, 0x00, 0xff, 0xdb, 0x00, 0x43,
    0x00, 0x08, 0x06, 0x06, 0x07, 0x06, 0x05, 0x08, 0x07, 0x07, 0x07, 0x09,
    0x09, 0x08, 0x0a, 0x0c, 0x14, 0x0d, 0x0c, 0x0b, 0x0b, 0x0c, 0x19, 0x12,
    0x13, 0x0f, 0x14, 0x1d, 0x1a, 0x1f, 0x1e, 0x1d, 0x1a, 0x1c, 0x1c, 0x20,
    0x24, 0x2e, 0x27, 0x20, 0x22, 0x2c, 0x23, 0x1c, 0x1c, 0x28, 0x37, 0x29,
    0x2c, 0x30, 0x31, 0x34, 0x34, 0x34, 0x1f, 0x27, 0x39, 0x3d, 0x38, 0x32,
    0x3c, 0x2e, 0x33, 0x34, 0x32, 0xff, 0xc0, 0x00, 0x0b, 0x08, 0x00, 0x01,
    0x00, 0x01, 0x01, 0x01, 0x11, 0x00, 0xff, 0xc4, 0x00, 0x1f, 0x00, 0x00,
    0x01, 0x05, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08,
    0x09, 0x0a, 0x0b, 0xff, 0xda, 0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3f,
    0x00, 0xbf, 0x80, 0xff, 0xd9
  ]);

  const testFileName = `test_rubaru_${Date.now()}.jpg`;

  try {
    console.log(`Uploading test image: ${testFileName} to ImageKit...`);
    const uploadResult = await imagekitService.uploadBuffer(
      sample1x1Jpg,
      testFileName,
      '/rubaru/tests',
      ['rubaru-test', 'verification']
    );

    console.log('✅ Upload Successful!');
    console.log('  File ID:', uploadResult.fileId);
    console.log('  ImageKit URL:', uploadResult.url);
    console.log('  Thumbnail URL:', uploadResult.thumbnailUrl);

    if (!uploadResult.url.includes('ik.imagekit.io/zjd5xircoy')) {
      throw new Error(`Expected URL to contain ik.imagekit.io/zjd5xircoy but got: ${uploadResult.url}`);
    }

    console.log('Cleaning up test file from ImageKit...');
    const deleteSuccess = await imagekitService.deleteFile(uploadResult.fileId);
    console.log('✅ Cleanup result:', deleteSuccess ? 'Deleted successfully' : 'Failed to delete');

    console.log('--- IMAGEKIT INTEGRATION TEST PASSED SUCCESSFULLY ---');
    process.exit(0);
  } catch (err) {
    console.error('❌ IMAGEKIT TEST FAILED:', err.message || err);
    process.exit(1);
  }
}

testImageKitIntegration();
